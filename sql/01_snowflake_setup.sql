USE ROLE REGRADAR_DEV;
USE WAREHOUSE REGRADAR_WH;
USE SCHEMA REGRADAR_DB.BRONZE;

-- File format for newline-delimited JSON (one record per line)
CREATE FILE FORMAT IF NOT EXISTS JSON_FF
  TYPE = JSON
  STRIP_OUTER_ARRAY = FALSE;

-- Internal stage = a folder inside Snowflake where raw files land
CREATE STAGE IF NOT EXISTS RAW_STAGE
  FILE_FORMAT = JSON_FF;

-- One raw table per source. Payload is the whole API record, untouched.
CREATE TABLE IF NOT EXISTS RAW_FEDERAL_REGISTER (
  PAYLOAD      VARIANT,
  SOURCE_FILE  STRING,
  LOADED_AT    TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW_REGULATIONS_GOV (
  PAYLOAD      VARIANT,
  SOURCE_FILE  STRING,
  LOADED_AT    TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW_CONGRESS (
  PAYLOAD      VARIANT,
  SOURCE_FILE  STRING,
  LOADED_AT    TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW_ECFR (
  PAYLOAD      VARIANT,
  SOURCE_FILE  STRING,
  LOADED_AT    TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

