-- =====================================================================
-- 6. Bronze objects: one stage and one raw table per source.
--    Every table has the same shape: the untouched record, its file, its load time.
-- =====================================================================
USE WAREHOUSE REGRADAR_WH;
USE SCHEMA REGRADAR_DB.BRONZE;

CREATE FILE FORMAT IF NOT EXISTS JSON_FF TYPE = JSON STRIP_OUTER_ARRAY = FALSE;
CREATE STAGE IF NOT EXISTS RAW_STAGE FILE_FORMAT = JSON_FF;

-- Regulations
CREATE TABLE IF NOT EXISTS RAW_FEDERAL_REGISTER     (PAYLOAD VARIANT, SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS RAW_ECFR                 (PAYLOAD VARIANT, SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS RAW_ECFR_VERSIONS        (PAYLOAD VARIANT, SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS RAW_REGULATIONS_GOV      (PAYLOAD VARIANT, SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS RAW_CONGRESS             (PAYLOAD VARIANT, SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS RAW_MA_REGULATIONS       (PAYLOAD VARIANT, SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
-- Industry
CREATE TABLE IF NOT EXISTS RAW_NAICS                (PAYLOAD VARIANT, SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
-- Location
CREATE TABLE IF NOT EXISTS RAW_COLLEGES             (PAYLOAD VARIANT, SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS RAW_CENSUS_ACS           (PAYLOAD VARIANT, SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS RAW_BUSINESS_PATTERNS    (PAYLOAD VARIANT, SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS RAW_MBTA_STATIONS        (PAYLOAD VARIANT, SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS RAW_BOSTON_NEIGHBORHOODS (PAYLOAD VARIANT, SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS RAW_BOSTON_FOOD_LICENSES (PAYLOAD VARIANT, SOURCE_FILE STRING, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());

SHOW TABLES IN SCHEMA REGRADAR_DB.BRONZE;
